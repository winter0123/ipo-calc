CREATE TABLE securities_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investor_id BIGINT NOT NULL REFERENCES investors(id) ON DELETE RESTRICT,
    securities_firm_id BIGINT NOT NULL REFERENCES securities_firms(id) ON DELETE RESTRICT,
    account_number VARCHAR(255) NOT NULL,
    account_name VARCHAR(255),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    deleted_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_securities_account_investor_id ON securities_accounts(investor_id);
CREATE INDEX idx_securities_account_status ON securities_accounts(status);

-- 투자자당 기본 계좌(is_default=TRUE)는 정확히 하나만 허용 (PostgreSQL partial unique index - 별도 문장)
CREATE UNIQUE INDEX uk_securities_account_default ON securities_accounts(investor_id) WHERE is_default = TRUE;