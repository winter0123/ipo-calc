-- 증권계좌 API 인증정보 테이블 생성
-- 목적: 증권사 조회 전용 API 연동에 필요한 앱키/앱시크릿/접근토큰을 계좌별로 암호화 저장한다.
-- securities_accounts와 1:1 관계(계좌당 앱키 1세트라는 외부 제약과 정합).
-- 계정 소유권 검증이 필수인 계정 소유 엔티티다.

CREATE TABLE securities_account_api_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    securities_account_id BIGINT NOT NULL REFERENCES securities_accounts(id) ON DELETE RESTRICT,
    api_provider VARCHAR(50) NOT NULL,
    app_key_encrypted TEXT NOT NULL,
    app_secret_encrypted TEXT NOT NULL,
    access_token_encrypted TEXT NULL,
    token_expires_at TIMESTAMP NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    deleted_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 인덱스: 계좌 ID로 인증정보 조회 시 사용
CREATE INDEX idx_api_cred_account_id ON securities_account_api_credentials(securities_account_id);

-- 조건부 유니크: 계좌 1개에 동일 api_provider ACTIVE 인증정보가 2건 이상 생성되지 않음 (별도 CREATE UNIQUE INDEX ... WHERE 문)
CREATE UNIQUE INDEX uk_api_cred_account_provider_active
    ON securities_account_api_credentials (securities_account_id, api_provider)
    WHERE status = 'ACTIVE';

-- 컬럼 설명
COMMENT ON TABLE securities_account_api_credentials IS '증권계좌별 브로커 API 인증정보(앱키/앱시크릿/접근토큰) 암호화 저장';
COMMENT ON COLUMN securities_account_api_credentials.id IS '기본키';
COMMENT ON COLUMN securities_account_api_credentials.securities_account_id IS '증권계좌 ID (FK, ON DELETE RESTRICT)';
COMMENT ON COLUMN securities_account_api_credentials.api_provider IS '브로커 어댑터 식별자 (예: KIS)';
COMMENT ON COLUMN securities_account_api_credentials.app_key_encrypted IS '앱키 암호문 (AES-256-GCM, Base64(IV+ciphertext))';
COMMENT ON COLUMN securities_account_api_credentials.app_secret_encrypted IS '앱시크릿 암호문 (AES-256-GCM, Base64(IV+ciphertext))';
COMMENT ON COLUMN securities_account_api_credentials.access_token_encrypted IS '접근토큰 암호문 (NULL 가능, AES-256-GCM, Base64(IV+ciphertext))';
COMMENT ON COLUMN securities_account_api_credentials.token_expires_at IS '토큰 만료 시각 (NULL 가능)';
COMMENT ON COLUMN securities_account_api_credentials.status IS '인증정보 상태 (ACTIVE/INACTIVE)';
COMMENT ON COLUMN securities_account_api_credentials.deleted_at IS '논리 삭제 시각 (NULL이면 활성)';
COMMENT ON COLUMN securities_account_api_credentials.created_at IS '생성 시각';
COMMENT ON COLUMN securities_account_api_credentials.updated_at IS '수정 시각';